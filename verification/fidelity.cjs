const {chromium}=require(process.env.PLAYWRIGHT_PATH || 'C:/Users/Fiatk/.codex/worktrees/shop-loading-motion/Khonnai/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:393,height:852}});
 await page.goto(require('node:url').pathToFileURL(path.join(__dirname,'../index.html')).href);
 await page.evaluate(()=>document.fonts.ready);
 const session=await page.context().newCDPSession(page);
 await session.send('DOM.enable');await session.send('CSS.enable');
 const document=await session.send('DOM.getDocument');
 const thai=await session.send('DOM.querySelector',{nodeId:document.root.nodeId,selector:'.hero .shop-name'});
 const {fonts}=await session.send('CSS.getPlatformFontsForNode',{nodeId:thai.nodeId});
 assert(fonts.length>0&&fonts.every(f=>f.familyName==='Google Sans'&&f.isCustomFont));
 const rect=selector=>page.locator(selector).first().boundingBox();
 assert.deepEqual(await rect('.hero'),{x:20,y:124,width:353,height:222});
 assert.equal((await rect('.quick-actions .circle')).width,64);
 await page.screenshot({path:path.join(__dirname,'fidelity-home.png')});
 await page.locator('[data-action="go:catalog"]').click();
 const tile=await page.locator('.product-tile .visual').first().boundingBox();
 assert.equal(tile.x,98);assert.equal(tile.y,118);assert.equal(tile.width,137.5);
 await page.screenshot({path:path.join(__dirname,'fidelity-catalog.png')});
 await page.locator('[data-action="quantity:B-220"]').click();
 await page.screenshot({path:path.join(__dirname,'fidelity-quantity.png')});
 await page.locator('[data-action=close]').click();
 await page.locator('[data-action="go:home"]').click();
 await page.locator('[data-action="go:add"]').click();
 await page.screenshot({path:path.join(__dirname,'fidelity-form.png')});
 await page.locator('[data-action="go:home"]').click();
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:path.join(__dirname,'fidelity-desktop.png')});
 fs.writeFileSync(path.join(__dirname,'fidelity-results.json'),JSON.stringify({passed:true,font:fonts,source:'khonnai-home-v1.figcraft',geometry:['393 × 852 screen','hero x20 y124 w353 h222','64px menu circles','catalog x98 y118 w137.5'],note:'Layout dimensions checked against source nodes. Google Sans intentionally replaces original font; dynamic data is not a fixed screenshot.'},null,2));
 await browser.close();console.log('PASS: source geometry and actual Google Sans Thai glyph rendering');
})().catch(e=>{console.error(e);process.exit(1)});
